# Type Conversion

x = 2                 # int
y = 3.5               # float
sum = x + y           # automatoic type conversion of x(2) from int to float (2.0 + 3.5 = 5.5)
print ("Sum:", sum)

# Type Casting 

x = int("2")          # manually converts string "2" to integer 2
y = float("3.5")      # manually converts string "3.5" to float 3.5
print ("x:", x)
print ("y:", y)

sum = x + y             # 2 + 3.5 = 5.5
print ("Sum:", sum)